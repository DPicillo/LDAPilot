//   - "openssl passwd -5/-6 -salt <salt> <pw>" (OpenSSL 3.5.7) and glibc
//     crypt(3) via perl (rounds=) in the ldapilot-samba-ad container,
//   - "pwdhash -s <scheme> secret" in the ldapilot-389ds container
//     (389-Directory/3.1.2),
//   - "slappasswd -h <scheme> -s secret" (OpenLDAP 2.4.57, contrib modules
//     pw-sha2, pw-pbkdf2, pw-argon2) in the ldapilot-openldap container.
//   - The "$5$saltstring"/"$6$saltstring" vectors are also the ones of
//     Drepper's SHA-crypt specification.

