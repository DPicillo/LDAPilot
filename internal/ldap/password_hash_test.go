func TestPasswordSchemeLabel(t *testing.T) {
	tests := map[string]string{
		"":                                   "",
		"secret":                             "cleartext",
		"{ssha}W6ph5Mm5Pz8GgiULbPgzG37mj9g=": "{SSHA}",
		"{CRYPT}$6$salt$hash":                "{CRYPT} SHA-512-crypt ($6$)",
		"{crypt}$5$salt$hash":                "{CRYPT} SHA-256-crypt ($5$)",
		"{CRYPT}abJnggxhB/yWI":               "{CRYPT}",
		"{CRYPT-SHA512}$6$s$h":               "{CRYPT-SHA512}", // 389DS's own tag
		"{PBKDF2-SHA512}1$a$b":               "{PBKDF2-SHA512}",
		"{crypt}$2b$10$abc":                  "{CRYPT} bcrypt ($2b$)",
	}
	for in, want := range tests {
		if got := PasswordSchemeLabel(in); got != want {
			t.Errorf("PasswordSchemeLabel(%q) = %q, want %q", in, got, want)
		}
	}
	// The label of a client-side SHA-crypt hash is the label of its picker option.
	for _, id := range []string{SchemeCryptSHA512, SchemeCryptSHA256, SchemeBcrypt} {
		v, err := HashPassword(id, "x")
		if err != nil {
			t.Fatal(err)
		}
		var label string
		for _, s := range PasswordSchemes() {
			if s.ID == id {
				label = s.Label
			}
		}
		if got := PasswordSchemeLabel(v); got != label {
			t.Errorf("PasswordSchemeLabel(HashPassword(%s)) = %q, want %q", id, got, label)
		}
	}
}

func TestPasswordSchemesCatalog(t *testing.T) {
	seen := map[string]bool{}
	for _, s := range PasswordSchemes() {
		if seen[s.ID] {
			t.Errorf("duplicate scheme %s", s.ID)
		}
		seen[s.ID] = true
		if s.Label == "" || s.Description == "" || len(s.Support) == 0 {
			t.Errorf("scheme %s lacks label, description or support", s.ID)
		}
	}
	if !seen[DefaultPasswordScheme] {
		t.Error("default scheme not in catalog")
	}
	// Callers get a copy.
	PasswordSchemes()[0].Support[0].Note = "changed"
	if PasswordSchemes()[0].Support[0].Note == "changed" {
		t.Error("PasswordSchemes returns shared slices")
	}
}

func decodedLen(s string) int {
	b, err := base64.StdEncoding.DecodeString(s)
	if err != nil {
		return -1
	}
	return len(b)
}

// verifyTestHash checks password against a stored userPassword value by
// recomputing it with the package's primitives.
func verifyTestHash(stored, password string) (bool, error) {
	if !strings.HasPrefix(stored, "{") {
		return stored == password, nil
	}
	end := strings.IndexByte(stored, '}')
	scheme, body := strings.ToUpper(stored[1:end]), stored[end+1:]
	digests := map[string]func() hash.Hash{
		"SHA": sha1.New, "SSHA": sha1.New, "MD5": md5.New, "SMD5": md5.New,
		"SHA256": sha256.New, "SSHA256": sha256.New, "SHA512": sha512.New, "SSHA512": sha512.New,
	}
	switch {
	case digests[scheme] != nil:
		raw, err := base64.StdEncoding.DecodeString(body)
		if err != nil {
			return false, err
		}
		size := digests[scheme]().Size()
		if len(raw) < size {
			return false, fmt.Errorf("too short")
		}
		return digestHash("{"+scheme+"}", digests[scheme], password, raw[size:]) == "{"+scheme+"}"+body, nil
	case scheme == "CRYPT" && strings.HasPrefix(body, "$2"):
		err := bcrypt.CompareHashAndPassword([]byte(body), []byte(password))
		if errors.Is(err, bcrypt.ErrMismatchedHashAndPassword) {
			return false, nil
		}
		return err == nil, err
	case scheme == "CRYPT":
		v, salt, rounds, err := parseShaCrypt(body)
		if err != nil {
			return false, err
		}
		return shaCrypt(v, password, salt, rounds) == body, nil
	case scheme == "PBKDF2-SHA512" || scheme == "PBKDF2-SHA256":
		parts := strings.Split(body, "$")
		if len(parts) != 3 {
			return false, fmt.Errorf("malformed")
		}
		iter, err := strconv.Atoi(parts[0])
		if err != nil {
			return false, err
		}
		salt, err := decodeAdaptedBase64(parts[1])
		if err != nil {
			return false, err
		}
		h := sha512.New
		if scheme == "PBKDF2-SHA256" {
			h = sha256.New
		}
		got, err := pbkdf2Hash("", h, password, salt, iter)
		if err != nil {
			return false, err
		}
		want, err := decodeAdaptedBase64(parts[2])
		if err != nil {
			return false, err
		}
		gotKey, _ := base64.StdEncoding.DecodeString(strings.Split(got, "$")[2])
		return string(gotKey) == string(want), nil
	case scheme == "ARGON2":
		// $argon2X$v=19$m=..,t=..,p=..$salt$hash
		parts := strings.Split(body, "$")
		if len(parts) != 6 {
			return false, fmt.Errorf("malformed")
		}
		var m, tm uint32
		var p uint8
		if _, err := fmt.Sscanf(parts[3], "m=%d,t=%d,p=%d", &m, &tm, &p); err != nil {
			return false, err
		}
		salt, err := base64.RawStdEncoding.DecodeString(parts[4])
		if err != nil {
			return false, err
		}
		want, err := base64.RawStdEncoding.DecodeString(parts[5])
		if err != nil {
			return false, err
		}
		var got []byte
		switch parts[1] {
		case "argon2id":
			got = argon2.IDKey([]byte(password), salt, tm, m, p, uint32(len(want)))
		case "argon2i":
			got = argon2.Key([]byte(password), salt, tm, m, p, uint32(len(want)))
		default:
			return false, fmt.Errorf("unsupported variant %s", parts[1])
		}
		return string(got) == string(want), nil
	}
	return false, fmt.Errorf("unsupported scheme %s", scheme)
}

// decodeAdaptedBase64 decodes standard base64 as well as the "adapted"
// variant of OpenLDAP's pw-pbkdf2 ('.' instead of '+', no padding).
func decodeAdaptedBase64(s string) ([]byte, error) {
	s = strings.ReplaceAll(s, ".", "+")
	return base64.RawStdEncoding.DecodeString(strings.TrimRight(s, "="))
}

