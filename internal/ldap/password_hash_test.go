func TestBcryptKnownAnswers(t *testing.T) {
	for _, tt := range bcryptKnownAnswers {
		stored := "{CRYPT}" + tt.hash
		if got := PasswordSchemeOf(stored); got != SchemeBcrypt {
			t.Errorf("PasswordSchemeOf(%s) = %q", stored, got)
		}
		if !IsHashedPasswordValue(stored) {
			t.Errorf("%s not recognized as hashed", stored)
		}
		ok, err := verifyTestHash(stored, tt.password)
		if err != nil || !ok {
			t.Errorf("%s does not verify %q (%v)", tt.hash, tt.password, err)
		}
		if ok, _ := verifyTestHash(stored, tt.password+"x"); ok {
			t.Errorf("%s verifies a wrong password", tt.hash)
		}
	}
}

func TestBcryptHash(t *testing.T) {
	v, err := HashPassword(SchemeBcrypt, "Grüße!Straße2026€")
	if err != nil {
		t.Fatal(err)
	}
	if !strings.HasPrefix(v, "{CRYPT}$2b$10$") {
		t.Fatalf("unexpected prefix: %s", v)
	}
	if err := bcrypt.CompareHashAndPassword([]byte(strings.TrimPrefix(v, "{CRYPT}")), []byte("Grüße!Straße2026€")); err != nil {
		t.Errorf("own hash does not verify: %v", err)
	}
	if cost, err := bcrypt.Cost([]byte(strings.TrimPrefix(v, "{CRYPT}"))); err != nil || cost != bcryptCost {
		t.Errorf("cost = %d (%v)", cost, err)
	}
	// Exactly 72 bytes work, longer passwords are refused (bcrypt would
	// silently ignore the rest).
	if _, err := HashPassword(SchemeBcrypt, strings.Repeat("a", 72)); err != nil {
		t.Errorf("72 bytes: %v", err)
	}
	if _, err := HashPassword(SchemeBcrypt, strings.Repeat("ä", 37)); err == nil {
		t.Error("74-byte password accepted")
	}
	if label := PasswordSchemeLabel(v); label != "{CRYPT} bcrypt ($2b$)" {
		t.Errorf("label %q", label)
	}
}
