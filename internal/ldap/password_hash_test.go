// TestServerHashesVerify recomputes server-generated hashes with this
// package's primitives, proving that the formats and algorithms match.
func TestServerHashesVerify(t *testing.T) {
	for _, stored := range storedHashes {
		ok, err := verifyTestHash(stored, "secret")
		if err != nil {
			t.Errorf("%s: %v", stored, err)
			continue
		}
		if !ok {
			t.Errorf("%s does not verify with the right password", stored)
		}
		if ok, _ := verifyTestHash(stored, "Secret"); ok {
			t.Errorf("%s verifies with a wrong password", stored)
		}
	}
}

// TestHashPasswordRoundTrip hashes with every catalog scheme and verifies the
// result, also with non-ASCII passwords.
func TestHashPasswordRoundTrip(t *testing.T) {
	for _, scheme := range PasswordSchemes() {
		for _, pw := range []string{"secret", "Grüße!Straße2026€", "a"} {
			value, err := HashPassword(scheme.ID, pw)
			if err != nil {
				t.Fatalf("HashPassword(%s): %v", scheme.ID, err)
			}
			if got := PasswordSchemeOf(value); got != scheme.ID {
				t.Errorf("PasswordSchemeOf(HashPassword(%s)) = %q", scheme.ID, got)
			}
			ok, err := verifyTestHash(value, pw)
			if err != nil || !ok {
				t.Errorf("%s: %q does not verify (%v)", scheme.ID, value, err)
			}
			if ok, _ := verifyTestHash(value, pw+"x"); ok {
				t.Errorf("%s: %q verifies with a wrong password", scheme.ID, value)
			}
		}
	}
}

func TestHashPasswordFormats(t *testing.T) {
	tests := []struct {
		scheme  string
		pattern func(string) bool
	}{
		{SchemeSSHA, func(v string) bool { return strings.HasPrefix(v, "{SSHA}") && decodedLen(v[6:]) == 20+digestSaltLen }},
		{SchemeSSHA512, func(v string) bool { return strings.HasPrefix(v, "{SSHA512}") && decodedLen(v[9:]) == 64+digestSaltLen }},
		{SchemeSHA, func(v string) bool { return v == "{SHA}5en6G6MezRroT3XKqkdPOmY/BfQ=" }},
		{SchemeSHA512, func(v string) bool {
			return v == "{SHA512}vSsar3708Jvp9Szi2NWZZ02Bqp1qRCFpbcTZPdBhnWgs5WtNZKnvCXdhztmeD2cmW192CF5bDufKRpayrW/isg=="
		}},
		{SchemeSHA256, func(v string) bool { return v == "{SHA256}K7gNU3sdo+OL0wNhqoVWhr3g6s1xYv72ol/pe/Unols=" }},
		{SchemeMD5, func(v string) bool { return v == "{MD5}Xr4ilOzQ4PCOq3aQ0qbuaQ==" }},
		{SchemeCryptSHA512, func(v string) bool { return strings.HasPrefix(v, "{CRYPT}$6$") && len(v) == len("{CRYPT}$6$")+16+1+86 }},
		{SchemeCryptSHA256, func(v string) bool { return strings.HasPrefix(v, "{CRYPT}$5$") && len(v) == len("{CRYPT}$5$")+16+1+43 }},
		{SchemePBKDF2SHA512, func(v string) bool {
			parts := strings.Split(strings.TrimPrefix(v, "{PBKDF2-SHA512}"), "$")
			return strings.HasPrefix(v, "{PBKDF2-SHA512}100000$") && len(parts) == 3 && decodedLen(parts[1]) == 16 && decodedLen(parts[2]) == 64
		}},
		{SchemePBKDF2SHA256, func(v string) bool {
			parts := strings.Split(strings.TrimPrefix(v, "{PBKDF2-SHA256}"), "$")
			return strings.HasPrefix(v, "{PBKDF2-SHA256}100000$") && len(parts) == 3 && decodedLen(parts[1]) == 16 && decodedLen(parts[2]) == 32
		}},
		{SchemeArgon2, func(v string) bool { return strings.HasPrefix(v, "{ARGON2}$argon2id$v=19$m=65536,t=3,p=1$") }},
		{SchemeBcrypt, func(v string) bool { return strings.HasPrefix(v, "{CRYPT}$2b$10$") && len(v) == len("{CRYPT}")+60 }},
		{SchemeCleartext, func(v string) bool { return v == "secret" }},
	}
	for _, tt := range tests {
		v, err := HashPassword(tt.scheme, "secret")
		if err != nil {
			t.Fatalf("%s: %v", tt.scheme, err)
		}
		if !tt.pattern(v) {
			t.Errorf("%s: unexpected format %q", tt.scheme, v)
		}
	}
	if _, err := HashPassword("NOPE", "x"); err == nil {
		t.Error("unknown scheme accepted")
	}
	// Scheme names are case-insensitive.
	if v, err := HashPassword("ssha", "x"); err != nil || !strings.HasPrefix(v, "{SSHA}") {
		t.Errorf("lower-case scheme: %q %v", v, err)
	}
	// Salts differ between calls.
	a, _ := HashPassword(SchemeSSHA, "x")
	b, _ := HashPassword(SchemeSSHA, "x")
	if a == b {
		t.Error("two SSHA hashes are identical: salt not random")
	}
}

